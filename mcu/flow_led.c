/*============================================
  实验一：花样流水灯实验
  芯片：AT89C51
  效果：8个LED从D8到D1轮流点亮，循环流动
  接法：P1口外接8个LED（D8~D1），共阳极
        （即单片机引脚输出0灯亮，输出1灯灭）
============================================*/
#include <reg52.h>   // 51单片机寄存器定义头文件
#include <intrins.h> // 包含循环右移函数_cror_的头文件

#define uchar unsigned char // 简写：uchar = unsigned char（无符号字符型，0~255）
#define uint  unsigned int  // 简写：uint = unsigned int（无符号整型，0~65535）

uchar i;   // 循环计数变量
uchar temp; // 保存P1口状态的变量

/*--------------------------------------------
  毫秒级延时函数
  参数z表示要延时多少毫秒
  内部是让CPU空转消耗时间（12MHz晶振下约1ms/次）
--------------------------------------------*/
void delay(uint z)
{
    uint x, y;
    for (x = z; x > 0; x--)
        for (y = 120; y > 0; y--);
}

/*--------------------------------------------
  主函数（程序从这里开始执行）
--------------------------------------------*/
void main()
{
    temp = 0x7f;  // 初始状态：0111 1111，最高位P1.7=0
                  // 共阳极接法下，输出0灯亮 → D8先亮
    P1 = temp;    // 把状态输出到P1口，点亮D8
    delay(1000);  // 停留1秒

    while (1)     // 无限循环，让灯一直流动
    {
        for (i = 0; i < 8; i++)
        {
            temp = _cror_(temp, 1); // 循环右移一位（"亮位"从左往右移动）
            P1 = temp;              // 输出新状态
            delay(1000);            // 停留1秒
        }
    }
}
